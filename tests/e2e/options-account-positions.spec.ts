import { expect, test } from "@playwright/test";

test("tracks an option on the account and detects edits from another device", async ({ page }, testInfo) => {
  const email = `option-positions-${Date.now()}-${testInfo.project.name}@example.test`;
  const registered = await page.request.post("/api/account/register", { data: { email, password: "Anatole2026!", display_name: "Synthetic test", accepted_terms: true, accepted_privacy: true } });
  expect(registered.status(), await registered.text()).toBe(201);
  const user = (await registered.json()).user as { id: string };
  const contract = { symbol: "SYNTH-CALL-100", underlying: "RY", market: "tsx", contract: null, side: "call", strike: 100, expiration: "2027-11-25", exchange: "TEST", bid: 1, ask: 2, last: 1.5, change: null, percent_change: null, volume: 10, open_interest: 20, implied_volatility: null, delta: null, gamma: null, theta: null, vega: null, in_the_money: null, source: "synthetic fixture", delayed: true };
  await page.route("**/api/anatole/api/v1/options/universe?**", (route) => route.fulfill({ json: { market: "tsx", items: [], source_statuses: [], generated_at: "2027-11-20T12:00:00Z", refresh_after_seconds: 3600 } }));
  await page.route("**/api/anatole/api/v1/options/chain?**", (route) => route.fulfill({ json: { market: "tsx", symbol: "RY", provider_symbol: "RY", name: "Synthetic RY", category: "Banks", exchange: "TEST", underlying_price: 100, requested_expiration: null, expirations: ["2027-11-25"], contracts: [contract], analytics: null, source_statuses: [], generated_at: "2027-11-20T12:00:00Z", refresh_after_seconds: 3600, stale: true } }));
  await page.goto("/options");
  await expect(page.getByRole("heading", { name: "RY · Synthetic RY" })).toBeVisible();
  await page.getByRole("button", { name: "Screener de contrats" }).click();
  await page.getByRole("region", { name: "Screener de contrats" }).getByRole("button", { name: "Suivre" }).click();
  const panel = page.getByRole("region", { name: "Positions d'options" });
  await panel.getByRole("button", { name: "Ouvrir les positions du compte" }).click();
  await expect(panel.getByText("Liste du compte", { exact: true })).toBeVisible();
  await panel.getByLabel("Nombre de contrats").fill("2");
  await panel.getByLabel("Multiplicateur vérifié").fill("100");
  await panel.getByLabel("Prime initiale par unité").fill("3");
  await panel.getByLabel("Devise ISO vérifiée").fill("CAD");
  await panel.getByLabel("Échéance vérifiée avec fuseau").fill("2027-11-25T16:00:00-05:00");
  await panel.getByLabel(/J'ai vérifié les spécifications/).check();
  await panel.getByRole("button", { name: "Enregistrer la position" }).click();
  await expect(panel.getByText("Enregistré dans le compte.")).toBeVisible();
  await panel.scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("account-option-positions-synthetic.png"), fullPage: true });
  const snapshot = await page.request.get("/api/account/option-positions", { headers: { "X-Anatole-Account": user.id } });
  expect(snapshot.status()).toBe(200);
  const saved = await snapshot.json();
  expect(saved.positions[0].quantity).toBe(2);
  const concurrent = await page.request.put("/api/account/option-positions", { data: { expected_account_id: user.id, expected_revision: saved.revision, positions: saved.positions } });
  expect(concurrent.status()).toBe(200);
  await panel.getByRole("button", { name: "Retirer du suivi" }).click();
  await expect(panel.getByText(/ont changé ailleurs/)).toBeVisible();
  await panel.getByRole("button", { name: "Actualiser les positions du compte" }).click();
  await panel.getByRole("button", { name: "Retirer du suivi" }).click();
  await expect(panel.getByText("Aucune position suivie.")).toBeVisible();
  expect((await page.request.delete("/api/account/delete", { data: { password: "Anatole2026!", confirmation: "SUPPRIMER" } })).status()).toBe(204);
});
